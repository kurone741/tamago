static void glyph(int x, int y, char c, int scale, bool on) {
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c < 0x20 || c > 'Z') c = '?';
    const uint8_t* g = kFont[c - 0x20];
    for (int col = 0; col < 5; col++)
        for (int row = 0; row < 7; row++)
            if (g[col] & (1 << row)) fill_rect(x + col * scale, y + row * scale, scale, scale, on);
}

int text_width(const char* s, int scale, int gap) {
    int n = strlen(s);
    return n ? n * (5 * scale + gap) - gap : 0;
}

void text(int x, int y, const char* s, int scale, int gap, bool on) {
    for (; *s; s++, x += 5 * scale + gap) glyph(x, y, *s, scale, on);
}

void text_centered(int y, const char* s, int scale, int gap, bool on) {
    text((W - text_width(s, scale, gap)) / 2, y, s, scale, gap, on);
}
